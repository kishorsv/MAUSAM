export function getThemeTokens(themeId: ThemeId, mode: 'dark' | 'light'): ThemeTokens {
  const themeGroup = THEME_TOKENS[themeId] || THEME_TOKENS['midnight-ai'];
  return themeGroup[mode] || themeGroup.dark;
}
